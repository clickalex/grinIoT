export function captureNow(state: SimState): SimState {
  if (!state.camera.enabled) return pushLog(state, "warn", "Camera", "Capture refused — the camera is disabled in settings.");
  if (state.camera.storagePct > 98) return pushLog(state, "warn", "Camera", "Capture refused — storage full. Export or purge the sequence.");
  const zone = state.zones[state.camera.captures % Math.max(1, state.zones.length)];
  const snapshot: Snapshot = {
    id: state.camera.seq,
    simMin: state.simMin,
    zoneId: zone?.id ?? "z1",
    zoneName: zone?.name ?? "Garden",
    moisture: zone?.moisture ?? 40,
    light: state.weather.light,
    growthIndex: state.camera.growthIndex,
    pest: null,
  };
  let next: SimState = {
    ...state,
    camera: {
      ...state.camera,
      seq: state.camera.seq + 1,
      captures: state.camera.captures + 1,
      lastCaptureSimMin: state.simMin,
      storagePct: round1(clamp(state.camera.storagePct + 0.6, 0, 100)),
      snapshots: [snapshot, ...state.camera.snapshots].slice(0, 40),
    },
  };
  next = pushLog(next, "info", "Camera", `Manual capture — ${snapshot.zoneName}, ${snapshot.moisture.toFixed(0)}% soil.`);
  return next;
}

export function reviewSnapshot(state: SimState, snapshotId: number, verdict: "confirmed" | "dismissed"): SimState {
  const snapshots = state.camera.snapshots.map(s => (s.id === snapshotId && s.pest ? { ...s, pest: { ...s.pest, status: verdict } } : s));
  const snapshot = state.camera.snapshots.find(s => s.id === snapshotId);
  let next: SimState = { ...state, camera: { ...state.camera, snapshots } };
  next = pushLog(next, verdict === "confirmed" ? "warn" : "ok", "Camera", `${snapshot?.zoneName ?? "Snapshot"}: ${snapshot?.pest?.name ?? "signature"} ${verdict} by human review.`);
  if (verdict === "confirmed") {
    next = addTaskIfNew(next, {
      title: `Treat ${snapshot?.zoneName ?? "the bed"} for ${snapshot?.pest?.name.toLowerCase() ?? "pest"}`,
      detail: "Confirmed from the camera review. Start with water blast and insecticidal soap; re-shoot in 48h.",
      kind: "care",
      dueSimMin: state.simMin + 240,
      zoneId: snapshot?.zoneId,
    });
  }
  return next;
}

