export function doseChannelNow(state: SimState, channelId: string): SimState {
  const channel = state.fertilizer.channels.find(c => c.id === channelId);
  if (!channel) return state;
  if (state.fertilizer.lockout) {
    return pushLog(state, "critical", "Fertilizer", `Dose on ${channel.name} refused — safety lockout is engaged.`);
  }
  if (!state.fertilizer.enabled || !channel.enabled) {
    return pushLog(state, "warn", "Fertilizer", `Dose on ${channel.name} refused — the channel or the injector is off.`);
  }
  const amount = Math.min(channel.doseMl, channel.reservoirMl);
  if (amount <= 0) return pushLog(state, "warn", "Fertilizer", `${channel.name}: reservoir empty — refill before dosing.`);
  const channels = state.fertilizer.channels.map(c =>
    c.id === channelId
      ? {
          ...c,
          reservoirMl: round1(c.reservoirMl - amount),
          todayMl: round1(c.todayMl + amount),
          totalMl: round1(c.totalMl + amount),
          lastDosedSimMin: state.simMin,
        }
      : c
  );
  let next: SimState = {
    ...state,
    fertilizer: { ...state.fertilizer, channels },
  };
  next = pushLog(next, "info", "Fertilizer", `${channel.name}: manual dose ${amount.toFixed(0)} ml injected${channel.zoneId ? ` on ${state.zones.find(z => z.id === channel.zoneId)?.name ?? channel.zoneId}` : ""}.`);
  return next;
}

