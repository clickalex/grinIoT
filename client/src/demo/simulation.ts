/** Demo affordance: fast-forward a node's power budget so the low-battery path is reachable. */
export function drainDeviceBattery(state: SimState, deviceId: string, simHours = 24): SimState {
  const device = state.devices.find(d => d.id === deviceId);
  if (!device || device.battery === null) return state;
  const used = Math.min(device.battery, simHours * 0.5);
  const devices = state.devices.map(d => (d.id === deviceId ? { ...d, battery: clamp((d.battery ?? 100) - used, 0, 100) } : d));
  const drained = devices.find(d => d.id === deviceId);
  let next: SimState = { ...state, devices };
  next = pushLog(next, drained && drained.battery !== null && drained.battery < 15 ? "warn" : "info", "Devices", `${device.name}: power budget advanced ${simHours}h — battery now ${drained?.battery?.toFixed(0)}%.`);
  if (drained && drained.battery !== null && drained.battery < 15) {
    next = pushAlert(next, "warn", `Low battery: ${device.name}`, `${drained.battery.toFixed(0)}% remaining. The node stretches its reporting interval; swap or charge it before autonomy degrades.`);
    next = { ...next, devices: next.devices.map(d => (d.id === deviceId && !d.fault ? { ...d, fault: `Low battery (${d.battery?.toFixed(0)}%) — reporting interval stretched` } : d)) };
  }
  return next;
}

